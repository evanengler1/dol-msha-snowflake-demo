-- Phase 1: infrastructure for the DOL MSHA demo. Run as ACCOUNTADMIN (or a role that can create
-- roles, warehouses and databases). Replace <YOUR_USER> before running.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DOL_MSHA_DEMO_ROLE;
GRANT ROLE DOL_MSHA_DEMO_ROLE TO USER <YOUR_USER>;
GRANT ROLE DOL_MSHA_DEMO_ROLE TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS DOL_MSHA_WH
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS DOL_MSHA_DEMO;
CREATE SCHEMA IF NOT EXISTS DOL_MSHA_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS DOL_MSHA_DEMO.TRANSFORMED;
CREATE SCHEMA IF NOT EXISTS DOL_MSHA_DEMO.ANALYTICS;

GRANT OWNERSHIP ON WAREHOUSE DOL_MSHA_WH TO ROLE DOL_MSHA_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE DOL_MSHA_DEMO TO ROLE DOL_MSHA_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA DOL_MSHA_DEMO.RAW TO ROLE DOL_MSHA_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA DOL_MSHA_DEMO.TRANSFORMED TO ROLE DOL_MSHA_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA DOL_MSHA_DEMO.ANALYTICS TO ROLE DOL_MSHA_DEMO_ROLE COPY CURRENT GRANTS;

